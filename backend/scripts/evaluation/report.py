"""Turn results/*.json into EVAL.md. Hand-written interpretation lives in eval/notes.md."""

import json
import statistics
from pathlib import Path
from typing import Any

from scripts.evaluation.gate import recommend, sweep
from scripts.evaluation.store import EVAL_DIR, RESULTS_DIR

REPO_ROOT = EVAL_DIR.parents[1]
EVAL_MD = REPO_ROOT / "EVAL.md"
NOTES = EVAL_DIR / "notes.md"
BACKENDS = ["groq", "jev", "jev+esc"]
# Groq list price for openai/gpt-oss-120b (USD per 1M tokens); Jev reports its own cost.
GROQ_PRICE_IN, GROQ_PRICE_OUT = 0.15, 0.60


def _load(name: str) -> Any | None:
    path = RESULTS_DIR / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _pct(value: float) -> str:
    return f"{value * 100:.0f}%"


def backend_metrics(result: dict[str, Any]) -> dict[str, Any]:
    cited = [s for s in result["sentences"] if s["cited"]]
    unsupported = [s for s in cited if s["label"] == "unsupported"]
    partial = [s for s in cited if s["label"] == "partial"]
    runs = result["runs"]
    ms = sorted(r["ms"] for r in runs if r["ok"] and r.get("called", True))
    groq_cost = (
        sum(r["input_tokens"] * GROQ_PRICE_IN + r["output_tokens"] * GROQ_PRICE_OUT for r in runs)
        / 1_000_000
    )
    jev_cost = sum(r["cost_usd"] or 0.0 for r in runs)
    return {
        "answers": len(runs),
        "failed": sum(1 for r in runs if not r["ok"]),
        "sentences": len(cited),
        "agreement": sum(s["label"] == s["verdict"] for s in cited) / max(len(cited), 1),
        "unsupported": len(unsupported),
        "let_through": sum(s["verdict"] == "supported" for s in unsupported),
        "partial_as_supported": sum(s["verdict"] == "supported" for s in partial),
        "partial": len(partial),
        "escalated": sum(r["escalated"] for r in runs),
        "median_ms": statistics.median(ms) if ms else 0.0,
        "p95_ms": ms[int(0.95 * (len(ms) - 1))] if ms else 0.0,
        "cost_per_100": (groq_cost + jev_cost) / max(len(runs), 1) * 100,
    }


def _gate_section(rows: list[dict[str, Any]]) -> list[str]:
    table = sweep(rows)
    best = recommend(table)
    lines = [
        "## Relevance gate (bge-small cosine)",
        "",
        f"{len(rows)} questions. Answered = best similarity ≥ threshold.",
        "",
        "| Threshold | Wrong-answer rate | Refusal rate | Near-misses answered |",
        "|---|---|---|---|",
    ]
    for row in table:
        mark = " **←**" if row is best else ""
        lines.append(
            f"| {row['threshold']:.3f}{mark} | {_pct(row['wrong_answer_rate'])} | "
            f"{_pct(row['refusal_rate'])} | {row['near_miss_answered']} |"
        )
    lines += ["", f"Recommended: **{best['threshold']:.3f}** (lowest wrong + refusal).", ""]
    lines += ["| Question | Kind | Top similarity | Top item |", "|---|---|---|---|"]
    for row in sorted(rows, key=lambda r: -r["top_similarity"]):
        lines.append(
            f"| {row['id']} | {row['kind']} | {row['top_similarity']:.3f} | {row['top_item']} |"
        )
    return [*lines, ""]


def _verifier_section(results: dict[str, dict[str, Any]]) -> list[str]:
    lines = [
        "## Verifier backends",
        "",
        "Over cited sentences only (uncited ones are `unsupported` by rule, no backend call). "
        "Latency is per answer that needed a backend call.",
        "",
        "| Backend | Agreement | Unsupported let through | Partial passed as supported | "
        "Escalated | Median / p95 latency | Cost per 100 answers | Failed calls |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name in BACKENDS:
        if name not in results:
            lines.append(f"| {name} | not run | | | | | | |")
            continue
        m = backend_metrics(results[name])
        lines.append(
            f"| {name} | {_pct(m['agreement'])} ({m['sentences']} sentences) | "
            f"{m['let_through']} of {m['unsupported']} | "
            f"{m['partial_as_supported']} of {m['partial']} | {m['escalated']} | "
            f"{m['median_ms']:.0f} / {m['p95_ms']:.0f} ms | ${m['cost_per_100']:.4f} | "
            f"{m['failed']} of {m['answers']} |"
        )
    return [*lines, ""]


def write_report() -> Path:
    lines = ["# Evaluation", "", "Generated by `uv run python -m scripts.eval report`.", ""]
    if NOTES.exists():
        lines += [NOTES.read_text(encoding="utf-8").strip(), ""]
    rows = _load("gate.json")
    if rows:
        lines += _gate_section(rows)
    results = {name: r for name in BACKENDS if (r := _load(f"verify_{name}.json"))}
    lines += _verifier_section(results)
    EVAL_MD.write_text("\n".join(lines), encoding="utf-8")
    return EVAL_MD
